/**
 * Converte deterministicamente un identificatore `snake_case` in `camelCase`.
 */
export function snakeToCamel(snake: string): string {
  return snake.replace(/_([a-z0-9])/g, (_, ch: string) => ch.toUpperCase());
}

function toPascalCase(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9]+/g, " ").trim();
  if (!cleaned) return "GeneratedModel";
  return cleaned
    .split(/\s+/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function mapRawTypeToContractType(rawType: unknown): ContractFieldType {
  if (typeof rawType !== "string") return "string";
  const lower = rawType.toLowerCase().trim();
  const parsed = ContractFieldTypeSchema.safeParse(lower);
  if (parsed.success) return parsed.data;
  if (lower === "integer" || lower === "number_int") return "int";
  if (lower === "number" || lower === "double" || lower === "decimal") return "float";
  if (lower === "bool") return "boolean";
  if (lower === "date" || lower === "timestamp") return "datetime";
  return "string";
}

/**
 * Normalizza un contratto in ingresso (`CrossDomainContract` oppure `ApiContract`)
 * estraendo la lista validata di `ParsedContractModel`.
 */
function normalizeContractModels(
  contract: CrossDomainContract | ApiContract
): ParsedCrossDomainContract {
  const parsed = CrossDomainContractSchema.parse(contract);
  if (parsed.models.length > 0) {
    return parsed;
  }

  // Fallback: estrae modelli dagli endpoint di ApiContractSchema se models è vuoto
  const derivedModels: ParsedContractModel[] = [];
  for (const ep of parsed.endpoints ?? []) {
    const schemaRecord = ep.responseBodySchema || ep.requestBodySchema;
    if (schemaRecord && typeof schemaRecord === "object") {
      const segment =
        ep.path
          .split("/")
          .filter((s) => s.length > 0 && !s.startsWith("{") && !s.startsWith(":"))
          .pop() ?? "Resource";
      const modelName = toPascalCase(segment.replace(/s$/, ""));
      const fields: ParsedContractField[] = Object.entries(schemaRecord).map(
        ([k, v]) => ({
          name: k
            .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
            .toLowerCase()
            .replace(/[^a-z0-9_]/g, "_"),
          type: mapRawTypeToContractType(
            typeof v === "object" && v !== null && "type" in v ? (v as any).type : v
          ),
          required:
            typeof v === "object" && v !== null && "required" in v
              ? Boolean((v as any).required)
              : true,
          description:
            typeof v === "object" && v !== null && typeof (v as any).description === "string"
              ? (v as any).description
              : undefined,
        })
      );
      if (fields.length > 0) {
        derivedModels.push(
          ContractModelSchema.parse({
            modelName,
            fields,
          })
        );
      }
    }
  }

  return {
    ...parsed,
    models: derivedModels,
  };
}

function mapPythonType(type: ContractFieldType): string {
  switch (type) {
    case "string":
      return "str";
    case "uuid":
      return "UUID";
    case "datetime":
      return "datetime";
    case "int":
      return "int";
    case "float":
      return "float";
    case "boolean":
      return "bool";
  }
}

function mapSwiftType(type: ContractFieldType): string {
  switch (type) {
    case "string":
      return "String";
    case "uuid":
      return "UUID";
    case "datetime":
      return "Date";
    case "int":
      return "Int";
    case "float":
      return "Double";
    case "boolean":
      return "Bool";
  }
}

/**
 * Genera i modelli Python Pydantic v2 idiomatici a partire dal contratto unificato.
 * Include `ConfigDict(populate_by_name=True, from_attributes=True)` e `Field(..., alias="camelCase")`.
 */
export function generatePydanticV2Models(
  contract: CrossDomainContract | ApiContract
): string {
  const normalized = normalizeContractModels(contract);

  const lines: string[] = [
    `# Auto-generated by Agentic Company OS — Cross-Domain Contract Synchronizer`,
    `# Contract: ${normalized.title} (v${normalized.version})`,
    `from datetime import datetime`,
    `from typing import Optional`,
    `from uuid import UUID`,
    `from pydantic import BaseModel, ConfigDict, Field`,
    ``,
  ];

  for (const model of normalized.models) {
    lines.push(`class ${model.modelName}(BaseModel):`);
    if (model.description) {
      lines.push(`    """${model.description}"""`);
    }
    lines.push(`    model_config = ConfigDict(`);
    lines.push(`        populate_by_name=True,`);
    lines.push(`        from_attributes=True,`);
    lines.push(`    )`);
    lines.push(``);

    for (const field of model.fields) {
      const basePyType = mapPythonType(field.type);
      const pyType = field.required ? basePyType : `Optional[${basePyType}]`;
      const camelAlias = snakeToCamel(field.name);
      const defaultExpr = field.required ? "..." : "default=None";
      const descPart = field.description
        ? `, description=${JSON.stringify(field.description)}`
        : "";

      if (camelAlias !== field.name) {
        lines.push(
          `    ${field.name}: ${pyType} = Field(${defaultExpr}, alias="${camelAlias}"${descPart})`
        );
      } else if (!field.required || field.description) {
        lines.push(`    ${field.name}: ${pyType} = Field(${defaultExpr}${descPart})`);
      } else {
        lines.push(`    ${field.name}: ${pyType}`);
      }
    }

    lines.push(``);
  }

  return lines.join("\n").trimEnd() + "\n";
}

/**
 * Genera le struct Swift 6 `Codable, Sendable, Hashable` (e `Identifiable` se presente `id`)
 * con proprietà `camelCase` ed enum `nonisolated private enum CodingKeys: String, CodingKey`.
 */
export function generateSwiftCodableModels(
  contract: CrossDomainContract | ApiContract
): string {
  const normalized = normalizeContractModels(contract);

  const lines: string[] = [
    `// Auto-generated by Agentic Company OS — Cross-Domain Contract Synchronizer`,
    `// Contract: ${normalized.title} (v${normalized.version})`,
    `import Foundation`,
    ``,
  ];

  for (const model of normalized.models) {
    const hasIdField = model.fields.some((f) => f.name === "id");
    const protocols = hasIdField
      ? "Codable, Sendable, Hashable, Identifiable"
      : "Codable, Sendable, Hashable";

    if (model.description) {
      lines.push(`/// ${model.description}`);
    }
    lines.push(`public struct ${model.modelName}: ${protocols} {`);

    for (const field of model.fields) {
      const camelName = snakeToCamel(field.name);
      const baseSwiftType = mapSwiftType(field.type);
      const swiftType = field.required ? baseSwiftType : `${baseSwiftType}?`;
      lines.push(`    public let ${camelName}: ${swiftType}`);
    }

    lines.push(``);
    lines.push(`    nonisolated private enum CodingKeys: String, CodingKey {`);
    for (const field of model.fields) {
      const camelName = snakeToCamel(field.name);
      if (camelName !== field.name) {
        lines.push(`        case ${camelName} = "${field.name}"`);
      } else {
        lines.push(`        case ${camelName}`);
      }
    }
    lines.push(`    }`);
    lines.push(`}`);
    lines.push(``);
  }

  return lines.join("\n").trimEnd() + "\n";
}

/**
 * Sincronizza in modo deterministico un contratto cross-domain generando il codice
 * Python Pydantic v2 e Swift 6 Codable/Sendable e, se `targetDir` è specificato e `!dryRun`,
 * salvandoli su disco tramite `atomicWriteFile` con backup `.bak`.
 */
export async function syncCrossDomainContracts(
  contract: CrossDomainContract | ApiContract,
  options?: ContractSyncOptions
): Promise<ContractSyncResult> {
  const normalized = normalizeContractModels(contract);
  const parsedOpts = ContractSyncOptionsSchema.parse(options ?? {});

  const pythonCode = generatePydanticV2Models(normalized);
  const swiftCode = generateSwiftCodableModels(normalized);

  const sha256Python = crypto
    .createHash("sha256")
    .update(pythonCode, "utf-8")
    .digest("hex");
  const sha256Swift = crypto
    .createHash("sha256")
    .update(swiftCode, "utf-8")
    .digest("hex");

  const writtenFiles: InjectedFileResult[] = [];

  if (parsedOpts.targetDir && !parsedOpts.dryRun) {
    const resolvedTargetDir = path.resolve(parsedOpts.targetDir);
    const pyFullPath = path.join(
      resolvedTargetDir,
      parsedOpts.pythonOutputRelativePath
    );
    const swiftFullPath = path.join(
      resolvedTargetDir,
      parsedOpts.swiftOutputRelativePath
    );

    const pyResult = await atomicWriteFile(pyFullPath, pythonCode, {
      backup: parsedOpts.backup,
    });
    const swiftResult = await atomicWriteFile(swiftFullPath, swiftCode, {
      backup: parsedOpts.backup,
    });

    writtenFiles.push(pyResult, swiftResult);
  }

  return ContractSyncResultSchema.parse({
    pythonCode,
    swiftCode,
    modelsSynced: normalized.models.map((m) => m.modelName),
    writtenFiles,
    sha256Python,
    sha256Swift,
  });
}
